/* Percorso SVG (spazio BASE) da una lista [lon, lat] */
export function pathOf(points, close = true) {
  let d = '';
  points.forEach(([lon, lat], i) => { d += (i ? 'L' : 'M') + (nx(lon) * BASE).toFixed(1) + ' ' + (ny(lat) * BASE).toFixed(1); });
  return d + (close ? 'Z' : '');
}
