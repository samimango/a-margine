/* lon/lat → coordinate normalizzate 0..1 (Web Mercator) */
export const nx = lon => (lon + 180) / 360;
export const ny = lat => { const s = Math.sin(lat * Math.PI / 180); return 0.5 - Math.log((1 + s) / (1 - s)) / (4 * Math.PI); };

